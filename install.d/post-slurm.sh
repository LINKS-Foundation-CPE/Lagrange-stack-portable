# shellcheck shell=bash
# Sourced by install.sh at the 'post' stage (install.d/README.md).

if [ "$WITH_SLURM" = 1 ]; then
  step "Switching quantum-api to job-portal-only"
  # In the HPC-only scenario SLURM owns authorization and accounting: the portal exists so users can find the jobs they
  # ran, and nothing else. JOB_PORTAL_ONLY makes quantum-api stop mounting the
  # management surface — projects, users, organizations, slots, reservations,
  # logs, budget events, announcements, notifications, /jobAuthorizer — and
  # stop billing; the dashboard reads the flag back from /config and hides what
  # is no longer there.
  #
  # It has to happen HERE rather than when .env is written: the seeding step
  # above drives exactly those endpoints, so a backend started with the flag on
  # would 404 its own seed. Unlike USERNAME_FORMAT the value is not frozen in
  # the database, so flipping it later — or back — costs only a restart.
  set_env quantum-api/.env JOB_PORTAL_ONLY true
  # `restart` would reuse the old environment; the container has to be recreated.
  (cd quantum-api && docker compose -f docker-compose.yaml -f docker-compose.tls-dev.yaml \
    up -d quantum-api)
  printf "waiting for quantum-api"
  for _ in $(seq 1 40); do
    curl -s --cacert "$CERT" -m 3 -o /dev/null "https://${HOST_IP}:8500/metrics/jobs" && break
    printf .; sleep 3
  done; echo
  portal=$(curl -s --cacert "$CERT" -m 10 "https://${HOST_IP}:8500/config" || true)
  case "$portal" in
    *'"jobPortalOnly":true'*) echo "  quantum-api is job-portal-only";;
    *) echo "  WARNING: /config does not report jobPortalOnly=true: ${portal:-<no response>}";;
  esac
fi

if [ "$WITH_SLURM" = 1 ] && [ -d slurm-docker-compose ]; then
  step "Installing the QPU token prolog/epilog scripts"
  # The cluster side of the sqed loop: the prolog mints a token and publishes the
  # record the gateway authenticates against, TaskProlog injects it into every
  # task, the epilog invalidates it. Ordinary shell scripts, nothing loaded into
  # slurmd — see prolog-epilog/README.md.
  PE_DIR="$(pwd)/prolog-epilog"
  SLURM_DIR="$(pwd)/slurm-docker-compose"
  cat > "${PE_DIR}/qpu-token.conf" <<EOF
# Generated by portable-deployment install.sh --with-slurm.
REDIS_HOST=jobs-redis-dev
REDIS_PORT=6379
REDIS_TIMEOUT=2
LICENSE_NAME=qpu
# Set this to the MaxTime of the partition carrying the qpu license.
MAX_WALLTIME_SECONDS=86400
GRACE_SECONDS=600
TOKEN_DIR=/run/qpu
TOKEN_PREFIX=sqed_
EOF
  cat > "${PE_DIR}/qpu-token.public" <<'EOF'
# Generated by portable-deployment install.sh --with-slurm. Read by TaskProlog,
# which runs as the job user and cannot read the root-only config above.
LICENSE_NAME=qpu
TOKEN_DIR=/run/qpu
EOF
  # Mount the scripts and their config into the headnode and both workers. A
  # docker-compose.override.yml is picked up automatically by `docker compose`.
  cat > slurm-docker-compose/docker-compose.override.yml <<EOF
# Generated by portable-deployment install.sh --with-slurm — do not edit; rerun
# the installer instead.
services:
  slurm-headnode:
    volumes:
      # slurm-docker-compose ships this mount COMMENTED OUT, so without it the
      # containers use the config baked into the image and the Prolog/Epilog/
      # TaskProlog lines added to slurm-config/slurm.conf below would be ignored.
      # The headnode stages /var/slurm_config into /etc/slurm and syncs it to the
      # workers, so mounting it here is enough.
      - ${SLURM_DIR}/slurm-config:/var/slurm_config:ro
      - ${PE_DIR}:/opt/sqed:ro
      - ${PE_DIR}/qpu-token.conf:/etc/sqed/qpu-token.conf:ro
      - ${PE_DIR}/qpu-token.public:/etc/sqed/qpu-token.public:ro
  slurm-worker1:
    volumes:
      - ${PE_DIR}:/opt/sqed:ro
      - ${PE_DIR}/qpu-token.conf:/etc/sqed/qpu-token.conf:ro
      - ${PE_DIR}/qpu-token.public:/etc/sqed/qpu-token.public:ro
  slurm-worker2:
    volumes:
      - ${PE_DIR}:/opt/sqed:ro
      - ${PE_DIR}/qpu-token.conf:/etc/sqed/qpu-token.conf:ro
      - ${PE_DIR}/qpu-token.public:/etc/sqed/qpu-token.public:ro
EOF
  # Jobs reach the gateway at https://host.docker.internal:8000 (a SAN on the
  # dev cert), whatever --ip is — so every node needs that name.
  for svc in slurm-headnode slurm-worker1 slurm-worker2; do
    python3 - slurm-docker-compose/docker-compose.override.yml "$svc" <<'HOSTS'
import sys
path, svc = sys.argv[1], sys.argv[2]
lines = open(path).read().splitlines(keepends=True)
i = lines.index(f"  {svc}:\n")
lines.insert(i + 1, '    extra_hosts:\n      - "host.docker.internal:host-gateway"\n')
open(path, "w").writelines(lines)
HOSTS
  done
  # Point slurm.conf at them, idempotently.
  SC=slurm-docker-compose/slurm-config/slurm.conf
  if [ -f "$SC" ] && ! grep -q '^Prolog=/opt/sqed/' "$SC"; then
    cat >> "$SC" <<'EOF'

# Sqed QPU token provisioning (portable-deployment --with-slurm): prolog/epilog
# scripts from the prolog-epilog repo, mounted at /opt/sqed. Never run a second
# provisioner (a SPANK plugin in plugstack.conf, say) alongside them.
Prolog=/opt/sqed/prolog.d/*
Epilog=/opt/sqed/epilog.d/*
TaskProlog=/opt/sqed/taskprolog/qpu-token
EOF
    echo "  configured Prolog/Epilog/TaskProlog in slurm-config/slurm.conf"
  else
    echo "  slurm.conf already points at /opt/sqed — leaving it alone"
  fi
  step "Starting the SLURM / sqed cluster (opt-in, best-effort)"
  (
    cd slurm-docker-compose || exit 1
    # Its own compose project: the directory name is generic enough to collide
    # with any other checkout of slurm-docker-compose on the host.
    #
    # And local image names: CONFIG.env names a registry the test bed's images
    # are not published to, which BuildKit would then contact. Nothing here
    # needs a registry, so build under a local prefix instead.
    export COMPOSE_PROJECT_NAME=portable-slurm REGISTRY=portable-local/
    # Build the images here rather than letting `up` fetch them: they are not
    # published, and `pull_policy: missing` means `up` would try to pull them on
    # a machine that has never built them.
    #
    # Two steps, because the headnode and worker images take the base image
    # through a BASE_IMAGE build arg and so need it to exist first. The base
    # compiles SLURM from source: on a cold cache this takes tens of minutes.
    echo "  building the SLURM base image (compiles SLURM from source — slow)"
    docker compose build vhpc-base-image \
      || echo "  NOTE: base image build failed — the cluster will not start"
    # These two print a harmless 'failed to configure registry cache importer'
    # ERROR: the compose file lists an unqualified image as cache_from, so
    # buildkit looks for it on Docker Hub. The build carries on and exits 0.
    echo "  building the headnode and worker images"
    docker compose build slurm-headnode slurm-worker1 slurm-worker2 \
      || echo "  NOTE: image build failed — the cluster will not start"
    echo "  docker compose up -d"
    docker compose up -d || echo "  NOTE: 'docker compose up -d' failed — see 'cd slurm-docker-compose && docker compose -p portable-slurm logs'"

    # Once slurmctld answers: register the qpu license (idempotent), give the
    # cluster user an account named after its project so its jobs are billed
    # there, and a home on the shared filesystem for job scripts and output.
    echo "  waiting for slurmctld..."
    for _ in $(seq 1 60); do
      docker compose exec -T slurm-headnode scontrol ping 2>/dev/null | grep -q UP && break
      sleep 5
    done
    if docker compose exec -T slurm-headnode scontrol ping 2>/dev/null | grep -q UP; then
      docker compose exec -T slurm-headnode bash -s 4 < scripts/setup-qpu-licenses.sh >/dev/null \
        && echo "  qpu license registered (request it as --licenses=qpu@qc_gateway:N)" \
        || echo "  WARNING: could not register the qpu license"
      docker compose exec -T slurm-headnode sacctmgr -i add account name="${CLUSTER_PROJECT}" \
        cluster=example-cluster >/dev/null 2>&1 || true
      docker compose exec -T slurm-headnode sacctmgr -i add user name="${CLUSTER_USER}" \
        account="${CLUSTER_PROJECT}" cluster=example-cluster >/dev/null 2>&1 || true
      echo "  SLURM user '${CLUSTER_USER}' in account '${CLUSTER_PROJECT}'"
      # The IQM client with Qiskit, which a job needs to submit a circuit, into
      # the venv the headnode shares with the workers (a named volume, so it
      # persists). Not through the repo's packages.yml: that installs before
      # slurmctld starts, and this one takes long enough (minutes) to fail the
      # headnode's healthcheck, so compose never starts the workers.
      echo "  installing iqm-client[qiskit] into the shared venv"
      docker compose exec -T slurm-headnode /opt/venv/bin/pip install -q \
        'iqm-client[qiskit]==34.0.3' >/dev/null \
        || echo "  WARNING: could not install iqm-client[qiskit] — jobs cannot submit circuits"
      docker compose exec -T slurm-headnode bash -c \
        "mkdir -p /shared/${CLUSTER_USER} && chown ${CLUSTER_USER}: /shared/${CLUSTER_USER}"
      docker compose cp "${CERT}" "slurm-headnode:/shared/${CLUSTER_USER}/keycloak.crt" >/dev/null
      echo "  /shared/${CLUSTER_USER} ready (with the dev CA as keycloak.crt)"
    else
      echo "  WARNING: slurmctld did not come up — license, account and /shared/${CLUSTER_USER} not set"
    fi
  )
  # The prolog needs the gateway's Redis, which lives on the gateway's network.
  # Only possible once the cluster network exists, i.e. after the up above.
  SLURM_NET="$(docker network ls --format '{{.Name}}' | grep -m1 'slurm.*slurm-net' || true)"
  if [ -n "$SLURM_NET" ]; then
    docker network connect "$SLURM_NET" jobs-redis-dev 2>/dev/null \
      && echo "  attached jobs-redis-dev to $SLURM_NET" \
      || echo "  jobs-redis-dev already on $SLURM_NET"
  else
    echo "  WARNING: no slurm-net network found — the prolog cannot reach Redis"
  fi
  cat <<'SLURMNOTE'
  NOTE: the SLURM deploy is best-effort; its compose project is 'portable-slurm'
        (cd slurm-docker-compose && docker compose -p portable-slurm ...).
        Jobs request the license as --licenses=qpu@qc_gateway:N (a REMOTE
        license; the bare name is rejected) — see docs/slurm-variant.md.
SLURMNOTE
fi
